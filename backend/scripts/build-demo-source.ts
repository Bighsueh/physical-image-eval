import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { buildValidSource, idFromImageName } from '../tests/fixtures/generate';
import { renderPlaceholderPng } from './demo/placeholder-png';

/**
 * Build the synthetic demo image source that `docker compose up` ingests out of the box:
 *
 *   npm run demo:source -w backend [-- <targetDir>]     (default: ../demo/source)
 *
 * It reuses the test fixture's layout (index + storyboards that pass every ingestion invariant) and
 * swaps its byte-stub PNGs for rendered placeholder comics. The target is wiped first, so the script
 * refuses any non-empty directory it did not create — a real image source must never be touched.
 */
const MARKER = '.demo-source';
const IMAGE_SIZE = 768;

const target = resolve(process.argv[2] ?? '../demo/source');

if (existsSync(target) && readdirSync(target).length > 0 && !existsSync(join(target, MARKER))) {
  console.error(`拒絕覆寫：${target} 不是由本腳本產生的示範來源（缺少 ${MARKER}）。`);
  process.exit(1);
}

buildValidSource(target);
writeFileSync(join(target, MARKER), 'Synthetic demo image source generated by backend/scripts/build-demo-source.ts\n');

const imageRoot = join(target, '_產圖');
const pngs = readdirSync(imageRoot, { recursive: true, encoding: 'utf8' }).filter((p) => p.endsWith('.png'));
for (const rel of pngs) {
  const blueprintId = idFromImageName(basename(rel));
  writeFileSync(join(imageRoot, rel), renderPlaceholderPng({ blueprintId, size: IMAGE_SIZE }));
}

console.log(`✅ 示範來源已產生：${target}（${pngs.length} 張示範圖）`);
